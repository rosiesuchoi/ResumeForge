import type { Resume } from "./types";

/**
 * Renders a Resume into Jake Gutierrez's "Jake's Resume" LaTeX template
 * (https://github.com/jakegut/resume, MIT, based on sb2nov/resume).
 * Pure string code so it runs in the browser (live preview) and on the server.
 */

const UNICODE_MAP: Record<string, string> = {
  "\u2018": "'", "\u2019": "'", "\u201C": "``", "\u201D": "''",
  "\u2013": "--", "\u2014": "---", "\u2022": "", "\u00A0": " ",
  "\u2026": "...", "\u2192": "$\\rightarrow$", "\u00D7": "$\\times$",
  "\u2264": "$\\leq$", "\u2265": "$\\geq$", "\u00B1": "$\\pm$", "\u2248": "$\\approx$",
};

/** Escape plain text for LaTeX body content. */
export function tex(input: string | undefined | null): string {
  if (!input) return "";
  let s = String(input).normalize("NFC");
  // Escape specials first (backslash via a sentinel so its braces survive).
  s = s
    .replace(/\\/g, "\u0000BS\u0000")
    .replace(/([&%$#_{}])/g, "\\$1")
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}")
    .replace(/</g, "\\textless{}")
    .replace(/>/g, "\\textgreater{}")
    .replace(/\u0000BS\u0000/g, "\\textbackslash{}");
  // Typographic unicode -> LaTeX
  s = s.replace(/[\u2018\u2019\u201C\u201D\u2013\u2014\u2022\u00A0\u2026\u2192\u00D7\u2264\u2265\u00B1\u2248]/g, (c) => UNICODE_MAP[c] ?? c);
  // Keep Latin-1 + Latin Extended-A (accents work with pdflatex utf8); drop emoji and other glyphs pdflatex can't set.
  s = s.replace(/[^\x09\x0A\x0D\x20-\x7E\u00A1-\u017F]/g, "");
  return s.trim();
}

/** Escape a URL for \href. */
function texUrl(url: string): string {
  return url.trim().replace(/\\/g, "").replace(/([%#&])/g, "\\$1").replace(/[{}]/g, "");
}

function normalizeUrl(url: string): string {
  const u = url.trim();
  if (!u) return "";
  if (/^mailto:/i.test(u) || /^https?:\/\//i.test(u)) return u;
  return `https://${u}`;
}

function displayUrl(url: string): string {
  return url.replace(/^https?:\/\//i, "").replace(/^www\./i, "").replace(/\/$/, "");
}

