function bullets(items: string[], indent = "      "): string {
  const clean = items.map((b) => tex(b)).filter(Boolean);
  if (!clean.length) return "";
  return [
    `${indent}\\resumeItemListStart`,
    ...clean.map((b) => `${indent}  \\resumeItem{${b}}`),
    `${indent}\\resumeItemListEnd`,
  ].join("\n");
}

function header(r: Resume): string {
  const parts: string[] = [];
  if (r.phone) parts.push(tex(r.phone));
  if (r.location) parts.push(tex(r.location));
  if (r.email) parts.push(`\\href{mailto:${texUrl(r.email)}}{\\underline{${tex(r.email)}}}`);
  for (const l of r.links) {
    if (!l.url) continue;
    const url = normalizeUrl(l.url);
    const label = l.label && !/^(linkedin|github|portfolio|website)$/i.test(l.label) ? l.label : displayUrl(url);
    parts.push(`\\href{${texUrl(url)}}{\\underline{${tex(label)}}}`);
  }
  return [
    "\\begin{center}",
    `    \\textbf{\\Huge \\scshape ${tex(r.name) || "Your Name"}} \\\\ \\vspace{1pt}`,
    `    \\small ${parts.join(" $|$ ")}`,
    "\\end{center}",
  ].join("\n");
}

function education(r: Resume): string {
  if (!r.education.length) return "";
  const rows = r.education.map((e) => {
    const extra = e.details.filter((d) => d.trim());
    return [
      "    \\resumeSubheading",
      `      {${tex(e.school)}}{${tex(e.location)}}`,
      `      {${tex(e.degree)}}{${tex(e.dates)}}`,
      extra.length ? bullets(extra) : "",
    ]
      .filter(Boolean)
      .join("\n");
  });
  return ["\\section{Education}", "  \\resumeSubHeadingListStart", ...rows, "  \\resumeSubHeadingListEnd"].join("\n");
}

function experienceLike(heading: string, items: Resume["experience"]): string {
  if (!items.length) return "";
  const rows = items.map((x) =>
    [
      "    \\resumeSubheading",
      `      {${tex(x.title)}}{${tex(x.dates)}}`,
      `      {${tex(x.company)}}{${tex(x.location)}}`,
      bullets(x.bullets),
    ]
      .filter(Boolean)
      .join("\n"),
  );
  return [`\\section{${heading}}`, "  \\resumeSubHeadingListStart", ...rows, "  \\resumeSubHeadingListEnd"].join("\n");
}

function projects(r: Resume): string {
  if (!r.projects.length) return "";
  const rows = r.projects.map((p) => {
    const name = p.link
      ? `\\href{${texUrl(normalizeUrl(p.link))}}{\\textbf{${tex(p.name)}}}`
      : `\\textbf{${tex(p.name)}}`;
    const tech = p.tech ? ` $|$ \\emph{${tex(p.tech)}}` : "";
    return ["      \\resumeProjectHeading", `          {${name}${tech}}{${tex(p.dates)}}`, bullets(p.bullets, "          ")]
      .filter(Boolean)
      .join("\n");
  });
  return ["\\section{Projects}", "    \\resumeSubHeadingListStart", ...rows, "    \\resumeSubHeadingListEnd"].join("\n");
}

function skills(r: Resume): string {
  const groups = r.skills.filter((s) => s.category.trim() && s.items.trim());
  if (!groups.length) return "";
  const lines = groups.map((g) => `     \\textbf{${tex(g.category)}}{: ${tex(g.items)}}`).join(" \\\\\n");
  return [
    "\\section{Technical Skills}",
    " \\begin{itemize}[leftmargin=0.15in, label={}]",
    "    \\small{\\item{",
    lines,
    "    }}",
    " \\end{itemize}",
  ].join("\n");
}

function certifications(r: Resume): string {
  const items = r.certifications.filter((c) => c.trim());
  if (!items.length) return "";
  return [
    "\\section{Certifications \\& Awards}",
    " \\begin{itemize}[leftmargin=0.15in, label={}]",
    "    \\small{\\item{",
    items.map((c) => `     ${tex(c)}`).join(" \\\\\n"),
    "    }}",
    " \\end{itemize}",
  ].join("\n");
}

export function resumeToLatex(r: Resume): string {
  const body = [
    header(r),
    education(r),
    experienceLike("Experience", r.experience),
    projects(r),
    experienceLike("Leadership \\& Activities", r.leadership),
    skills(r),
    certifications(r),
  ]
    .filter(Boolean)
    .join("\n\n%-----------\n\n");
  return `${PREAMBLE}\n\\begin{document}\n\n${body}\n\n%-------------------------------------------\n\\end{document}\n`;
}

/** Bracketed placeholders like [X%] that the user still has to fill in. */
export function findPlaceholders(r: Resume): string[] {
  const all = [
    ...r.experience.flatMap((e) => e.bullets),
    ...r.projects.flatMap((p) => p.bullets),
    ...r.leadership.flatMap((e) => e.bullets),
  ];
  const found: string[] = [];
  for (const b of all) for (const m of b.matchAll(/\[[^\]]{1,30}\]/g)) found.push(m[0]);
  return found;
}

/** Flatten a resume into plain text (used for ATS keyword matching). */
export function resumeToText(r: Resume): string {
  return [
    r.name,
    ...r.education.flatMap((e) => [e.school, e.degree, ...e.details]),
    ...r.experience.flatMap((e) => [e.title, e.company, ...e.bullets]),
    ...r.projects.flatMap((p) => [p.name, p.tech, ...p.bullets]),
    ...r.leadership.flatMap((e) => [e.title, e.company, ...e.bullets]),
    ...r.skills.map((s) => `${s.category}: ${s.items}`),
    ...r.certifications,
  ].join("\n");
}
